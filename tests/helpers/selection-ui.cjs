const assert = require("node:assert/strict");
const path = require("node:path");
const { copy } = require("./chrome-fixture.cjs");

module.exports = async function verifySelectionUI({ page, fixture, artifacts }) {
  let checks = 0;
  const equal = (...args) => { assert.equal(...args); checks += 1; };
  const deepEqual = (...args) => { assert.deepEqual(...args); checks += 1; };
  const originalRoot = copy(fixture.root);
  const originalMetadata = copy(fixture.storage.metadataByUrl);
  const originalSettings = copy(fixture.storage.settings);
  const originalUndo = fixture.storage.lastUndo && copy(fixture.storage.lastUndo);
  const originalTabs = copy(fixture.tabsCreated);
  const bar = page.locator(".ba-selection-bar");
  const rows = page.locator(".ba-bookmark-list .ba-bookmark-row");
  const row = (id) => page.locator(`.ba-bookmark-list [data-bookmark-id="${id}"]`);
  const checkbox = (id) => row(id).locator(".ba-select-bookmark");
  const title = (id) => row(id).locator(".ba-bookmark-title");
  const countRows = (count) => page.waitForFunction((expected) => document.querySelectorAll(".ba-bookmark-list .ba-bookmark-row").length === expected, count);
  const selected = () => rows.filter({ has: page.locator(".ba-select-bookmark:checked") }).evaluateAll((items) => items.map((item) => item.dataset.bookmarkId));
  const refresh = async () => {
    const before = await page.evaluate(() => globalThis.__managerReplies);
    await page.evaluate(() => globalThis.__bookmarkChange());
    await page.waitForFunction((old) => globalThis.__managerReplies > old, before);
  };
  const afterLoad = async (action) => {
    const before = await page.evaluate(() => globalThis.__managerReplies);
    await action();
    await page.waitForFunction((old) => globalThis.__managerReplies > old, before);
  };
  const seed = ["Alpha", "Beta", "Gamma", "Delta"].map((name, index) => ({
    id: `selection-${index}`, parentId: "101", index: index + 1, title: `Batch ${name}`,
    url: `https://example.test/selection/${index}`, dateAdded: Date.UTC(2026, 1, index + 1)
  }));
  fixture.find("101").children.push(...seed);
  await refresh();
  await countRows(6);
  equal(await bar.isVisible(), false);
  await title("selection-3").click({ modifiers: ["Control"] });
  deepEqual(await selected(), ["selection-3"]);
  equal(await page.locator(".ba-select-all").evaluate((node) => node.indeterminate), true);
  await title("selection-1").click({ modifiers: ["Shift"] });
  deepEqual(await selected(), ["selection-3", "selection-2", "selection-1"]);
  await title("selection-0").click({ modifiers: ["Meta"] });
  equal((await selected()).length, 4);
  await title("selection-0").click({ modifiers: ["Control"] });
  equal((await selected()).length, 3);
  equal(fixture.tabsCreated.length, originalTabs.length);
  const more = page.getByRole("button", { name: "More selected actions", exact: true });
  const menu = page.locator(".ba-menu");
  await more.focus();
  await page.keyboard.press("Enter");
  await menu.waitFor({ state: "visible" });
  const triggerRect = await more.boundingBox();
  const menuRect = await menu.boundingBox();
  equal(Math.abs(menuRect.y - triggerRect.y - triggerRect.height - 4) < 1, true);
  equal(await menu.locator("button").first().evaluate((node) => node === document.activeElement), true);
  await page.screenshot({ path: path.join(artifacts, "selection-more-keyboard.png"), animations: "disabled" });
  await page.keyboard.press("ArrowDown");
  equal(await menu.locator("button").last().evaluate((node) => node === document.activeElement), true);
  await page.keyboard.press("Escape");
  equal(await more.evaluate((node) => node === document.activeElement), true);
  await page.keyboard.press("Enter");
  await page.keyboard.press("Tab");
  equal(await menu.isVisible(), false);
  equal(await page.getByRole("button", { name: "Clear selection", exact: true }).evaluate((node) => node === document.activeElement), true);
  await page.screenshot({ path: path.join(artifacts, "selection-desktop.png"), animations: "disabled" });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(artifacts, "selection-390.png"), animations: "disabled" });
  equal(await bar.evaluate((node) => node.scrollWidth <= node.clientWidth + 1), true);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.keyboard.press("Escape");
  equal(await bar.isVisible(), false);
  equal(await page.locator("#bookmark-admin-overlay").count(), 1);
  await afterLoad(() => title("selection-0").click());
  equal(fixture.tabsCreated.length, originalTabs.length + 1);
  await checkbox("selection-3").focus();
  await page.keyboard.press("Space");
  deepEqual(await selected(), ["selection-3"]);
  equal(await checkbox("selection-3").evaluate((node) => node === document.activeElement), true);
  await page.keyboard.press("Control+a");
  equal((await selected()).length, 6);
  equal(await page.locator(".ba-select-all").evaluate((node) => node.indeterminate), false);
  await page.locator(".ba-sort").selectOption("title");
  equal((await selected()).length, 6);
  await page.getByRole("button", { name: "Clear selection", exact: true }).click();
  await checkbox("selection-2").click();
  await checkbox("selection-1").focus();
  await page.keyboard.press("Shift+Space");
  deepEqual((await selected()).sort(), ["selection-1", "selection-2", "selection-3"]);
  await page.keyboard.press("Escape");
  await page.locator(".ba-sort").selectOption("newest");
  await checkbox("selection-3").click();
  await checkbox("selection-2").click();
  await page.locator(".ba-search").fill("Batch Delta");
  await countRows(1);
  deepEqual(await selected(), ["selection-3"]);
  await page.locator(".ba-search").fill("");
  await countRows(6);
  deepEqual(await selected(), ["selection-3"]);
  await page.locator(".ba-search").fill("no matching bookmarks");
  await countRows(0);
  equal(await bar.isVisible(), false);
  await page.locator(".ba-search").fill("");
  await countRows(6);
  deepEqual(await selected(), []);
  await checkbox("selection-3").click();
  await page.locator('[data-folder-id="102"] .ba-name').click();
  await countRows(1);
  equal(await bar.isVisible(), false);
  await page.getByRole("button", { name: /^All in Library/ }).click();
  await countRows(6);
  await page.getByRole("tab", { name: /^All Bookmarks/ }).click();
  await countRows(14);
  await checkbox("401").click();
  equal(await bar.innerText().then((text) => /read-only/.test(text)), true);
  for (const action of ["move", "rename", "delete"]) equal(await bar.locator(`[data-bulk-action="${action}"]`).isDisabled(), true);
  await page.keyboard.press("Delete");
  equal(await page.locator(".ba-action-dialog").count(), 0);
  await page.keyboard.press("Escape");
  await page.getByRole("tab", { name: /^Library/ }).click();
  await countRows(6);

  const dialog = page.locator(".ba-action-dialog");
  const openAction = (action) => bar.locator(`[data-bulk-action="${action}"]`).click();
  const waitSubmit = () => page.waitForFunction(() => document.querySelector(".ba-action-submit")?.disabled === false);
  await checkbox("selection-1").click();
  await checkbox("selection-0").click();
  await openAction("move");
  await dialog.getByRole("combobox", { name: "Destination folder", exact: true }).selectOption("102");
  await waitSubmit();
  equal(await dialog.locator(".ba-bulk-preview-status").innerText(), "2 will change");
  for (let index = 0; index < 8; index += 1) {
    await page.keyboard.press(index % 2 ? "Shift+Tab" : "Tab");
    equal(await dialog.evaluate((node) => node.contains(document.activeElement)), true);
  }
  await page.screenshot({ path: path.join(artifacts, "selection-move.png"), animations: "disabled" });
  await page.keyboard.press("Escape");
  await dialog.waitFor({ state: "hidden" });
  equal((await selected()).length, 2);
  equal(fixture.find("selection-0").parentId, "101");
  await openAction("move");
  await dialog.getByRole("combobox", { name: "Destination folder", exact: true }).selectOption("102");
  await waitSubmit();
  await afterLoad(() => dialog.getByRole("button", { name: "Move", exact: true }).click());
  equal(fixture.find("selection-0").parentId, "102");
  equal(fixture.find("selection-1").parentId, "102");
  equal(await bar.isVisible(), false);
  equal(await page.locator(".ba-select-all").evaluate((node) => node === document.activeElement), true);
  await afterLoad(() => page.locator(".ba-undo").click());
  equal(fixture.find("selection-0").parentId, "101");
  await checkbox("selection-0").click();
  await checkbox("selection-1").click();
  await page.keyboard.press("F2");
  const mutationsBeforePreview = fixture.mutations.length;
  await dialog.getByRole("textbox", { name: "Rename text", exact: true }).fill("[Read] ");
  await waitSubmit();
  equal(fixture.mutations.length, mutationsBeforePreview);
  equal(await dialog.locator(".ba-rename-preview").innerText().then((text) => text.includes("[Read] Batch Alpha")), true);
  await page.screenshot({ path: path.join(artifacts, "selection-rename.png"), animations: "disabled" });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(artifacts, "selection-rename-390.png"), animations: "disabled" });
  equal(await dialog.evaluate((node) => node.scrollWidth <= node.clientWidth + 1), true);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await afterLoad(() => dialog.getByRole("button", { name: "Rename", exact: true }).click());
  equal(fixture.find("selection-0").title, "[Read] Batch Alpha");
  equal(fixture.find("selection-1").title, "[Read] Batch Beta");
  await afterLoad(() => page.locator(".ba-undo").click());
  equal(fixture.find("selection-0").title, "Batch Alpha");
  await checkbox("selection-2").click();
  await checkbox("selection-3").click();
  await page.keyboard.press("Delete");
  await waitSubmit();
  await page.screenshot({ path: path.join(artifacts, "selection-delete.png"), animations: "disabled" });
  const dangerContrast = await dialog.locator(".ba-action-submit").evaluate((node) => {
    const rgb = (value) => value.match(/[\d.]+/g).slice(0, 3).map(Number);
    const luminance = (values) => values.map((value) => {
      const channel = value / 255;
      return channel <= 0.04045 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4;
    }).reduce((sum, value, index) => sum + value * [0.2126, 0.7152, 0.0722][index], 0);
    const foreground = luminance(rgb(getComputedStyle(node).color));
    const background = luminance(rgb(getComputedStyle(node.closest("form")).backgroundColor));
    return (Math.max(foreground, background) + 0.05) / (Math.min(foreground, background) + 0.05);
  });
  equal(dangerContrast >= 4.5, true);
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click();
  equal((await selected()).length, 2);
  await openAction("delete");
  await waitSubmit();
  await afterLoad(() => dialog.getByRole("button", { name: "Delete", exact: true }).click());
  await countRows(4);
  equal(fixture.find("selection-2"), undefined);
  equal(fixture.find("selection-3"), undefined);
  await afterLoad(() => page.locator(".ba-undo").click());
  await countRows(6);
  deepEqual(fixture.find("101").children.map((node) => node.url), ["https://example.test/200", ...seed.map((node) => node.url)]);
  const partial = [0, 1].map((index) => ({ id: `partial-${index}`, parentId: "101", index: index + 5,
    title: `Partial failure ${index}`, url: `https://example.test/partial/${index}`, dateAdded: Date.UTC(2026, 2, index + 1) }));
  fixture.find("101").children.push(...partial);
  await refresh();
  await countRows(8);
  await checkbox("partial-0").click();
  await checkbox("partial-1").click();
  const nativeRemove = fixture.chrome.bookmarks.remove;
  fixture.chrome.bookmarks.remove = (id, callback) => { if (id === "partial-1") throw new Error("Synthetic delete failure"); nativeRemove(id, callback); };
  await openAction("delete");
  await waitSubmit();
  await afterLoad(() => dialog.getByRole("button", { name: "Delete", exact: true }).click());
  equal(await dialog.locator(".ba-action-error").innerText().then((text) => /Completed 1.*Synthetic delete failure/.test(text)), true);
  equal(await dialog.getByRole("button", { name: "Cancel", exact: true }).evaluate((node) => node === document.activeElement), true);
  equal(fixture.storage.lastUndo.snapshots.length, 1);
  await page.screenshot({ path: path.join(artifacts, "selection-partial-error.png"), animations: "disabled" });
  fixture.chrome.bookmarks.remove = nativeRemove;
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click();
  await afterLoad(() => page.locator(".ba-undo").click());
  equal(await page.locator(".ba-select-all").evaluate((node) => node === document.activeElement), true);
  fixture.find("101").children = fixture.find("101").children.filter((node) => !node.url.startsWith("https://example.test/partial/"));
  fixture.find("101").children.forEach((node, index) => { node.index = index; });
  await refresh();
  await countRows(6);
  await checkbox("selection-0").click();
  await checkbox("selection-1").click();
  fixture.find("101").children = fixture.find("101").children.filter((node) => node.id !== "selection-0");
  fixture.find("101").children.forEach((node, index) => { node.index = index; });
  await refresh();
  await countRows(5);
  deepEqual(await selected(), ["selection-1"]);
  await openAction("rename");
  await dialog.getByRole("textbox", { name: "Rename text", exact: true }).fill("Reviewed ");
  await waitSubmit();
  fixture.find("selection-1").title = "Manual title while confirming";
  await refresh();
  await dialog.getByRole("button", { name: "Rename", exact: true }).click();
  await dialog.locator(".ba-action-error").filter({ hasText: /changed/ }).waitFor();
  equal(fixture.find("selection-1").title, "Manual title while confirming");
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click();
  await page.getByRole("button", { name: "Clear selection", exact: true }).click();
  fixture.find("101").children = fixture.find("101").children.filter((node) => node.id === "200");
  fixture.find("101").children[0].index = 0;
  fixture.storage.metadataByUrl = originalMetadata;
  if (originalUndo) fixture.storage.lastUndo = originalUndo;
  else delete fixture.storage.lastUndo;
  fixture.tabsCreated.splice(0, fixture.tabsCreated.length, ...originalTabs);
  await refresh();
  await countRows(2);
  if (await page.getByRole("button", { name: "Collapse all folders", exact: true }).isEnabled()) await page.getByRole("button", { name: "Collapse all folders", exact: true }).click();
  deepEqual(fixture.root, originalRoot);
  deepEqual(fixture.storage.settings, originalSettings);
  fixture.mutations.length = 0;
  return checks;
};
